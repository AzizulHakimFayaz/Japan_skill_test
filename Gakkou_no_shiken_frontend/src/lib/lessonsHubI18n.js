export function getLessonsHubText(lang) {
  return LESSONS_HUB_UI[lang] || LESSONS_HUB_UI.en;
}

export function getLocalizedTopic(topic, lang) {
  if (!lang || lang === 'en') {
    return { title: topic.title, description: topic.description };
  }
  const entry = LEARN_TOPIC_I18N[topic.slug]?.[lang];
  if (!entry) {
    return { title: topic.title, description: topic.description };
  }
  return { title: entry[0], description: entry[1] };
}
